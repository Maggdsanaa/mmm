    private fun n(l: String, p: String, d: String, vararg a: Double, ordered: Boolean = false,
                  review: Boolean = false, note: String = "", tol: Double = 1e-6,
                  dis: List<String> = emptyList(), s: String = "") =
        Question(p, a.toList(), d, l, ordered, null, review, note, tol, dis, st(s))
    private fun e(l: String, p: String, note: String = "", s: String = "") =
        Question(p, emptyList(), "∅ (لا يوجد حل)", l, note = note, steps = st(s))
    private fun iv(l: String, p: String, d: String, s: String) =
        Question(p, emptyList(), d, l, interval = d, steps = st(s))

    private fun sysQ(l: String, v1: String, v2: String, a1: Int, b1: Int, c1: Int, a2: Int, b2: Int, c2: Int,
                     title: String = "حل المعادلتين:", cramer: Boolean = false): Question {
        val d = a1 * b2 - a2 * b1
        val x = (c1 * b2 - c2 * b1).toDouble() / d
        val y = (a1 * c2 - a2 * c1).toDouble() / d
        val steps = if (cramer) Steps.cramer2(a1, b1, c1, a2, b2, c2, v1, v2)
                    else Steps.sys(a1, b1, c1, a2, b2, c2, v1, v2)
        return Question("$title\n${Steps.eq(a1, v1, b1, v2, c1)}\n${Steps.eq(a2, v1, b2, v2, c2)}",
            listOf(x, y), "($x, $y)", l, ordered = true, steps = steps)
    }

    private fun poly(a: Int, b: Int, c: Int): String {
        fun co(v: Int) = if (abs(v) == 1) "" else "${abs(v)}"
        val sb = StringBuilder()
        sb.append(if (a < 0) "−" else "").append(co(a)).append("x²")
        if (b != 0) sb.append(if (b < 0) " − " else " + ").append(co(b)).append("x")
        if (c != 0) sb.append(if (c < 0) " − " else " + ").append(abs(c))
        return sb.toString()
    }

    private fun qd(a: Int, b: Int, c: Int, note: String = ""): Question {
        val d = (b * b - 4 * a * c).toDouble()
        val r1 = (-b + sqrt(d)) / (2.0 * a); val r2 = (-b - sqrt(d)) / (2.0 * a)
        return Question("حل المعادلة: ${poly(a, b, c)} = 0", listOf(r1, r2), "", "quad",
            note = note, steps = Steps.quad(a.toDouble(), b.toDouble(), c.toDouble()))
    }

